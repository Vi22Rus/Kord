-- IT-02/2.7: cooldown event revisions are independent, coalesced.
local KR={}
assert(loadfile("KordRotation/Core/EventBus.lua"))("KordRotation",KR)
local bus=KR.EventBus
assert(bus:GetItemCooldownRevision()==0)
local notifications=0
assert(bus:Subscribe("itemCooldown","test",function() notifications=notifications+1 end))
assert(bus:HandleEvent("BAG_UPDATE_COOLDOWN"))
assert(bus:GetItemCooldownRevision()==1 and bus:GetInventoryRevision()==0)
assert(bus:HandleEvent("BAG_UPDATE_DELAYED"))
assert(bus:GetItemCooldownRevision()==2 and bus:GetInventoryRevision()==1)
assert(bus:HandleEvent("ACTIONBAR_UPDATE_COOLDOWN"))
assert(bus:GetItemCooldownRevision()==3)
assert(bus:HandleEvent("UNIT_SPELLCAST_SUCCEEDED","player"))
assert(bus:GetItemCooldownRevision()==4)
assert(bus:HandleEvent("UNIT_SPELLCAST_SUCCEEDED","focus")==false)
assert(bus:GetItemCooldownRevision()==4)
assert(bus:HandleEvent("ZONE_CHANGED_NEW_AREA"))
assert(bus:GetItemCooldownRevision()==5)
assert(bus:HandleEvent("PLAYER_REGEN_ENABLED"))
assert(bus:GetItemCooldownRevision()==6)
assert(bus:HandleEvent("INVALID_EVENT")==false)
assert(notifications==0)
bus:Flush()
assert(notifications==1)
assert(bus:RequestItemCooldownRefresh("explicit_test")==7)
assert(bus:Status().itemCooldownRevision==7)
assert(bus:Status().itemCooldownLastReason=="explicit_test")
bus:Flush()
assert(notifications==2)
print("item_cooldown_revision_mock PASS")

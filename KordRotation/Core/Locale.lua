-- Do not silently overwrite client locale: it is determined via GetLocale().
local locale = type(GetLocale) == "function" and GetLocale() or "enUS"
local aliases = { enGB="enUS", esMX="esES", ptPT="ptBR" }
locale = aliases[locale] or locale
if not translations[locale] then locale = "enUS" end
KR.locale = locale
KR.clientLocale = locale

-- Saved locale selection applies to all UI on the next interface reload.
function KR:ApplyLocalePreference(preference)
    if preference=="ruRU" or preference=="enUS" then
        self.locale=preference
    else
        self.locale=self.clientLocale
    end
end

function KR:L(key)
    return (translations[self.locale] and translations[self.locale][key])
        or translations.enUS[key] or key
end

function KR:Format(key, ...)
    local fmt = self:L(key)
    local ok, result = pcall(string.format, fmt, ...)
    return ok and result or fmt
end

function KR:GetLocalizedTree(classToken, index)
    if not classToken or not index then return self:L("SPEC_UNKNOWN") end
    return self:L("SPEC_"..classToken.."_"..index)
end

